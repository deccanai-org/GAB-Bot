"""Local source parsing and exact stored links. This module never fetches URLs."""

from __future__ import annotations

import html
import re
from dataclasses import dataclass
from html.parser import HTMLParser
from urllib.parse import urlsplit


@dataclass(frozen=True)
class SourceLink:
    label: str
    url: str
    location: str = ""


def safe_url(value: str) -> bool:
    try:
        parsed = urlsplit(value)
        return (
            parsed.scheme in {"https", "http"}
            and bool(parsed.hostname)
            and parsed.username is None
            and parsed.password is None
            and not any(c.isspace() or c in "<>\\" for c in value)
        )
    except ValueError:
        return False


class LocalHTML(HTMLParser):
    """Preserve href destinations, including query strings; ignore executable content."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.links = []
        self.hidden = 0
        self.anchor = None

    def handle_starttag(self, tag, attrs):
        if tag in {"script", "style"}:
            self.hidden += 1
        if self.hidden:
            return
        if tag in {"p", "div", "li", "br", "h1", "h2", "h3", "h4", "tr"}:
            self.parts.append("\n")
        if tag == "a":
            href = dict(attrs).get("href", "")
            self.anchor = (href, len(self.parts), self.getpos()[0])

    def handle_endtag(self, tag):
        if tag in {"script", "style"}:
            self.hidden = max(0, self.hidden - 1)
            return
        if self.hidden:
            return
        if tag == "a" and self.anchor:
            href, start, line = self.anchor
            label = "".join(self.parts[start:]).strip() or "Source link"
            if safe_url(href):
                self.links.append(SourceLink(label, href, f"HTML line {line}"))
                self.parts[start:] = [f"[{label}]({href})"]
            self.anchor = None
        if tag in {"p", "div", "li", "h1", "h2", "h3", "h4", "tr"}:
            self.parts.append("\n")

    def handle_data(self, data):
        if not self.hidden:
            self.parts.append(data)

    @property
    def text(self):
        return re.sub(r"\n[ \t]*\n+", "\n\n", "".join(self.parts)).strip()


def html_text(text: str) -> str:
    parser = LocalHTML()
    parser.feed(text)
    parser.close()
    return parser.text


def extract_links(text: str, location: str = "") -> tuple[SourceLink, ...]:
    links = []
    if re.search(r"<a\b", text, re.I):
        parser = LocalHTML()
        parser.feed(text)
        return tuple(dict.fromkeys(parser.links))
    for label, url in re.findall(r"\[([^\]]+)\]\((https?://[^\s)]+)\)", text):
        if safe_url(url):
            links.append(SourceLink(label, url, location))
    for url in re.findall(r"https?://[^\s<>\"\]]+", text):
        url = html.unescape(url.rstrip(".,;)").split('"', 1)[0])
        if safe_url(url) and not any(link.url == url for link in links):
            links.append(SourceLink("Source link", url, location))
    return tuple(dict.fromkeys(links))


def prompt_text(text: str) -> str:
    """URLs are attached by code, never generated by the model."""
    if re.search(r"<a\b", text, re.I):
        text = html_text(text)
    text = re.sub(r"\[([^\]]+)\]\(https?://[^\s)]+\)", r"\1 [stored link]", text)
    return re.sub(r"https?://[^\s<>]+", "[stored link]", text)
